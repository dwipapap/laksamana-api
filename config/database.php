<?php

use Illuminate\Support\Str;
use Pdo\Mysql;

/*
| Connections are generated, not hand-written:
|  - `core`: the new unified database owned by Laravel (migrations run ONLY here).
|  - `legacy_<env>`: one per existing laksamana-office database, from config/laksamana.php.
|    Each cPanel DB has its own MySQL user, so every credential can be overridden per
|    database (DB_<ENV>_USERNAME / _PASSWORD), falling back to DB_LEGACY_* then DB_*.
|  - EMULATE_PREPARES=false matches every legacy backend (a named placeholder used twice
|    in one statement fails with HY093 there too, so ported SQL behaves identically).
*/
$laksamanaMysql = function (array $over = []) {
    return array_merge([
        'driver' => 'mysql',
        'host' => env('DB_HOST', '127.0.0.1'),
        'port' => env('DB_PORT', '3306'),
        'database' => env('DB_DATABASE', 'lakk5493_laksamana_core'),
        'username' => env('DB_USERNAME', 'root'),
        'password' => env('DB_PASSWORD', ''),
        'unix_socket' => env('DB_SOCKET', ''),
        'charset' => 'utf8mb4',
        'collation' => 'utf8mb4_unicode_ci',
        'prefix' => '',
        'prefix_indexes' => true,
        'strict' => true,
        'engine' => 'InnoDB',
        'options' => extension_loaded('pdo_mysql') ? [
            PDO::ATTR_EMULATE_PREPARES => false,
        ] : [],
    ], $over);
};

$laksamanaConnections = ['core' => $laksamanaMysql()];
$laksamanaRegistry = require __DIR__.'/laksamana.php';
$laksamanaDbs = [];
$laksamanaServerMode = [];
foreach ($laksamanaRegistry['modules'] as $m) {
    $laksamanaDbs[$m['env']] = $m['database'];
    // A shared connection (event+ticketing) keeps the server mode if ANY module on it asks.
    $laksamanaServerMode[$m['env']] = ($laksamanaServerMode[$m['env']] ?? false) || ! empty($m['server_sql_mode']);
}
foreach ($laksamanaRegistry['extra_connections'] as $envKey => $dbName) {
    $laksamanaDbs[$envKey] = $dbName;
}
foreach ($laksamanaDbs as $envKey => $dbName) {
    $laksamanaConnections['legacy_'.strtolower($envKey)] = $laksamanaMysql([
        'host' => env("DB_{$envKey}_HOST", env('DB_LEGACY_HOST', env('DB_HOST', '127.0.0.1'))),
        'database' => env("DB_{$envKey}_DATABASE", $dbName),
        'username' => env("DB_{$envKey}_USERNAME", env('DB_LEGACY_USERNAME', env('DB_USERNAME', 'root'))),
        'password' => env("DB_{$envKey}_PASSWORD", env('DB_LEGACY_PASSWORD', env('DB_PASSWORD', ''))),
    ] + ($laksamanaServerMode[$envKey] ?? false ? [
        // strict=null: Laravel leaves sql_mode alone. DB_<ENV>_SQL_MODE pins one (local runs).
        'strict' => null,
        'modes' => array_filter(explode(',', (string) env("DB_{$envKey}_SQL_MODE", ''))) ?: null,
    ] : []));
}

return [

